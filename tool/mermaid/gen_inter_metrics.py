#!/usr/bin/env python3
"""Writes app/lib/ui/render/mermaid/inter_metrics.dart: Inter's advance widths.

    pip install fonttools          # once
    python3 tool/mermaid/gen_inter_metrics.py

Why: a Mermaid diagram is laid out in an isolate (`layoutMermaidOffThread`),
where `TextPainter` does not exist, so label widths come from a table of the
font the diagram is painted in (`InterTextMeasurer`). Regular serves weights
below 600, Bold the rest. The output is committed, so building the app never
needs Python.
"""
import pathlib

from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parents[2]
FONTS = ROOT / "app" / "assets" / "fonts"
OUT = ROOT / "app" / "lib" / "ui" / "render" / "mermaid" / "inter_metrics.dart"

# Basic Latin, Latin-1, Latin Extended-A, the Vietnamese horn letters and
# their stacked-diacritic block, general punctuation, currency, arrows, and
# the two ticks agents put in labels.
RANGES = [
    (0x0020, 0x007E),
    (0x00A0, 0x00FF),
    (0x0100, 0x017F),
    (0x01A0, 0x01A1),
    (0x01AF, 0x01B0),
    (0x1EA0, 0x1EF9),
    (0x2010, 0x2027),
    (0x2030, 0x203A),
    (0x20AB, 0x20AB),
    (0x2190, 0x2199),
    (0x2713, 0x2713),
    (0x2717, 0x2717),
]


def table(path: pathlib.Path):
    font = TTFont(path)
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    advances = {}
    for lo, hi in RANGES:
        for cp in range(lo, hi + 1):
            name = cmap.get(cp)
            if name is not None:
                advances[cp] = hmtx[name][0]
    return font["head"].unitsPerEm, advances


def emit(name: str, advances: dict) -> str:
    rows = []
    items = sorted(advances.items())
    for i in range(0, len(items), 8):
        rows.append("  " + " ".join(f"0x{cp:04X}: {adv}," for cp, adv in items[i : i + 8]))
    return f"const Map<int, int> {name} = {{\n" + "\n".join(rows) + "\n};\n"


def main():
    upm_regular, regular = table(FONTS / "Inter-Regular.ttf")
    upm_bold, bold = table(FONTS / "Inter-Bold.ttf")
    assert upm_regular == upm_bold, "Regular and Bold must share unitsPerEm"
    text = (
        "// Generated by tool/mermaid/gen_inter_metrics.py. Do not edit.\n"
        "//\n"
        "// Advance widths of Inter (assets/fonts), in font units, for the code points\n"
        "// a diagram label uses. See InterTextMeasurer.\n"
        "library;\n\n"
        f"const int interUnitsPerEm = {upm_regular};\n\n"
        + emit("interRegularAdvance", regular)
        + "\n"
        + emit("interBoldAdvance", bold)
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"{OUT.relative_to(ROOT)}: {len(regular)} regular, {len(bold)} bold, upm {upm_regular}")


if __name__ == "__main__":
    main()
